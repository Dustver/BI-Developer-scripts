# АНАЛИЗ ОШИБОК И РЕКОМЕНДАЦИИ ПО УСОВЕРШЕНСТВОВАНИЮ:
# 1. КРИТИЧЕСКАЯ ОШИБКА — ПОПЫТКА УДАЛЕНИЯ КАТАЛОГОВ: `Get-ChildItem -Path $path -Recurse` без флага `-File`
#    выбирает как файлы, так и папки. Если папка модифицировалась раньше $delolder, Remove-Item попытается
#    удалить папку со всеми внутри лежащими логи-файлами, в том числе свежими!
#    РЕШЕНИЕ: Добавить параметр `-File` (`Get-ChildItem -Path $path -File -Recurse`).
# 2. ОТСУТСТВИЕ ОБРАБОТКИ ОШИБОК (TRY/CATCH): При попытке удалить файл, открытый процессом Qlik Sense
#    (файлы логов часто заблокированы), скрипт выбросит необработанную ошибку в консоль.
#    РЕШЕНИЕ: Обернуть `Remove-Item` в `try { ... } catch { Write-Warning ... }`.
# 3. НЕИСПОЛЬЗУЕМЫЕ ПЕРЕМЕННЫЕ: Присутствует закомментированная переменная `#$путь` на кириллице.
# ==============================================================================

# Указываем путь к временной папке пользователя
#$путь = "C:\ProgramData\Qlik\Sense\Log"
$path = "C:\ProgramData\Qlik\Sense\Log"

# Указываем количество месяцев, старше которых файлы будут удалены
$months = 6

# Получаем текущую дату и вычитаем из нее указанное количество месяцев
$delolder = (Get-Date).AddMonths(-$months)

# Получаем все файлы в указанной папке и её подпапках, старше заданной даты
$files = Get-ChildItem -Path $path -Recurse | Where-Object { $_.LastWriteTime -lt $delolder }

# Удаляем каждый файл
foreach ($file in $files) {
    Remove-Item $file.FullName -Force
}

Write-Host "Deletion Complete."
